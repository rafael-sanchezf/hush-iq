// Copies the frozen Manhattan sample (packages/model/noise_score/data/manhattan_baseline.json, M12) into the
// site, trimmed to what the browser replay of engine v2 needs: each building's weight, floors, whether the
// ground floor is commercial, and its facade-neutral levels per source and time slot. Run it when the
// baseline is rebuilt: `npm run baseline`. The output is committed so a Vercel build of apps/web alone works.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = fileURLToPath(new URL('../../../packages/model/noise_score/data/manhattan_baseline.json', import.meta.url));
const out = fileURLToPath(new URL('../src/lib/replay/manhattan.json', import.meta.url));

const SOURCES = ['street', 'nightlife', 'building', 'sirens', 'construction'];
const WINDOWS = ['night', 'early', 'day'];

const doc = JSON.parse(readFileSync(src, 'utf8'));
const trimmed = {
  note: 'Generated by scripts/sync-baseline.mjs from packages/model/noise_score/data/manhattan_baseline.json. Do not edit.',
  as_of: doc.as_of,
  config_sha: doc.config_sha,
  apartments: doc.universe.units,
  // levels: 15 numbers, source-major (street night, early, day, nightlife night, ...).
  samples: doc.samples.map((s) => ({
    w: s.weight ?? 1,
    f: s.floors ?? null,
    c: Boolean(s.commercial),
    l: SOURCES.flatMap((n) => WINDOWS.map((w) => s.levels[n][w])),
  })),
};
writeFileSync(out, JSON.stringify(trimmed) + '\n');
console.log(`wrote ${trimmed.samples.length} buildings to ${out}`);
